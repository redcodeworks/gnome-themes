"""Write a scheme's accent token maps (<scheme>/accents/<accent>.{dark,light}.sed and accents/list).

  python3 -I tools/accent-maps-gen.py <scheme-dir> <accent-dir>

<accent-dir>/<accent>/... holds the scheme re-generated with each of its accents (six terminal colours, plus orange where the scheme has one) (the generators'
--accent-dir option: the recolour is re-run with the accent anchor, the accent exact entries and the text-on-accent
colour switched). This script compares each file with the default-accent output token by token (hex and rgba()
forms, lower-cased) and writes the map from the default accent's tokens to the accent's tokens, per variant: the same
map serves gtk-3.0, gtk-4.0, gnome-shell and (both maps together) the libadwaita file of that variant. The maps are
plain sed scripts so installing needs only sed: two phases (token -> placeholder, placeholder -> new token) so a new
value can never be rewritten again by a later rule. Every map is then VERIFIED by running sed on the default files and
comparing with the directly generated accent files. Different stock shades can collapse to one default token (8-bit
rounding) and then need slightly different accent tokens; the map takes the most frequent one, so such tokens may be
off by 1-3 units per channel (invisible; counted in the output, never more than TOL). Anything else aborts.
"""
import tempfile, sys, os, re, subprocess, tomllib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from collections import Counter
from themegen import TOK
TOL = 3     # 3 of 255 (about 1 %) per channel: Rose Pine's dark pine-green accent needs 3 for two collapsed tints

d, adir = sys.argv[1].rstrip('/'), sys.argv[2]
with open(d + '/palette.toml', 'rb') as f: M = tomllib.load(f)
dflt, dark_only = M['default_accent'], M['dark_only']
light_only = M.get('light_only', False)
names = list(next(iter(M['accents'].values())))

def default_path(rel):
    if rel.startswith('libadwaita/'): return d + '/libadwaita/gtk.css'
    if rel.startswith('gtk-'): return '%s/themes/%s/%s' % (d, M['gtk_name'], rel)
    return '%s/themes/%s' % (d, rel)
def variant(rel):
    if rel.startswith('libadwaita/'): return 'both'
    if rel.endswith('gtk-dark.css') or '-Dark/' in rel: return 'dark'
    if rel.startswith('gtk-'): return 'dark' if dark_only else 'light'
    return 'light'

def toks(text): return [(m.start(), m.group(0).lower()) for m in TOK.finditer(text)]

def tokmap(dtext, atext, rel):
    """{default token: accent token} for one file; variant of each position for libadwaita."""
    dt, at = toks(dtext), toks(atext)
    assert len(dt) == len(at) and TOK.sub('', dtext) == TOK.sub('', atext), '%s: accent output differs in more than colour tokens' % rel
    cut = (dtext.find('\n@media') if '\n@media' in dtext else 0) if rel.startswith('libadwaita/') else None
    out = {'dark': {}, 'light': {}}
    for (pos, x), (_, y) in zip(dt, at):
        if x == y: continue
        v = variant(rel)
        if v == 'both': v = 'light' if (pos < cut or light_only) else 'dark'      # the toast rule after the media block is dark too
        out[v].setdefault(x, Counter())[y] += 1
    return out

def nums(t):
    return [int(n) for n in re.findall(r'\d+', t)[:3]] if t.startswith('rgb') else [int(t[i:i + 2], 16) for i in (1, 3, 5)]
def close(a, b):
    if a == b: return True
    if a.startswith('rgb') != b.startswith('rgb'): return False
    if a.startswith('rgb') and a.rsplit(',', 1)[-1] != b.rsplit(',', 1)[-1]: return False
    return all(abs(x - y) <= TOL for x, y in zip(nums(a), nums(b)))

def sed_text(m, label, tag):
    esc = lambda t: t.replace('.', '\\.')
    L = ['# candy-for-gnome accent map (%s): tokens of the default accent output -> this accent. Generated by tools/accent-maps-gen.py.' % label]
    for i, k in enumerate(sorted(m)): L.append('s|%s|@@%s%d@@|gI' % (esc(k), tag, i))
    for i, k in enumerate(sorted(m)): L.append('s|@@%s%d@@|%s|g' % (tag, i, m[k]))
    return '\n'.join(L) + '\n'

def apply(path, *maps):
    cmd = ['sed']
    for m in maps: cmd += ['-f', m]
    return subprocess.run(cmd + [path], capture_output=True, text=True, check=True).stdout

os.makedirs(d + '/accents', exist_ok=True)
for old in os.listdir(d + '/accents'): os.remove(d + '/accents/' + old)
rels = sorted(os.path.relpath(os.path.join(r, f), adir + '/' + dflt) for r, _, fs in os.walk(adir + '/' + dflt) for f in fs)
for a in names:
    maps = {'dark': {}, 'light': {}}; votes = {'dark': {}, 'light': {}}; approx = 0
    for rel in rels:
        dtext, atext = open(default_path(rel)).read(), open('%s/%s/%s' % (adir, a, rel)).read()
        for v, m in tokmap(dtext, atext, rel).items():
            for k, c in m.items(): votes[v].setdefault(k, Counter()).update(c)
    for v in votes:
        for k, c in votes[v].items():
            best = c.most_common(1)[0][0]; maps[v][k] = best
            if len(c) > 1:
                approx += sum(n for t, n in c.items() if t != best)
                if not all(close(best, t) for t in c): sys.exit('accent %s: token %s maps to far-apart tokens %s' % (a, k, dict(c)))
    variants = ['light'] if light_only else (['dark'] if dark_only else ['dark', 'light'])
    for v in variants:
        body = '# default accent: nothing to rewrite\n' if a == dflt else sed_text(maps[v], '%s %s %s' % (os.path.basename(d), a, v), v[0].upper())
        open('%s/accents/%s.%s.sed' % (d, a, v), 'w').write(body)
    # verify: sed(default file) == generated accent file
    for rel in rels:
        v = variant(rel)
        files = ['%s/accents/%s.%s.sed' % (d, a, x) for x in ((['light'] if light_only else (['light', 'dark'] if not dark_only else ['dark'])) if v == 'both' else [v])]
        if v == 'both' and len(files) == 2:
            # libadwaita: the light map applies to the part before the @media block, the dark map to the rest (a token both variants share maps differently)
            txt = open(default_path(rel)).read(); cut = txt.find('\n@media')
            hp, tp = tempfile.mktemp(), tempfile.mktemp()
            open(hp, 'w').write(txt[:cut]); open(tp, 'w').write(txt[cut:])
            got = apply(hp, files[0]) + apply(tp, files[1]); os.remove(hp); os.remove(tp)
        else: got = apply(default_path(rel), *files)
        want = open('%s/%s/%s' % (adir, a, rel)).read()
        gt, wt = toks(got), toks(want)
        if TOK.sub('', got) != TOK.sub('', want) or len(gt) != len(wt) or not all(close(x[1], y[1]) for x, y in zip(gt, wt)): sys.exit('VERIFY FAILED: %s accent %s %s (sed result differs from the generated file)' % (os.path.basename(d), a, rel))
    print('%-8s %4d dark tokens%s verified on %d files (%d token occurrences approximated)' % (a, len(maps['light' if light_only else 'dark']), '' if dark_only or light_only else ', %4d light tokens,' % len(maps['light']), len(rels), approx))
with open(d + '/accents/list', 'w') as f:
    f.write('# name dark-hex light-hex (- = none) [default]: written by tools/accent-maps-gen.py\n')
    for a in names:
        f.write('%s %s %s%s\n' % (a, M['accents']['light' if light_only else 'dark'][a]['color'], '-' if (dark_only or light_only) else M['accents']['light'][a]['color'], ' default' if a == dflt else ''))
