#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Install, list, update, remove and switch themes (this repo) and icon sets (several icon repos, see
# tools/icon-sources.conf) in the user's home. Needs only bash and git. Checklists are a built-in terminal UI (SPACE toggles).
#   themectl.sh <themes|icons> <install|list|update|remove|switch> [name] [accent]
# A theme is a top-level directory of this repo (a scheme, e.g. gruvbox-material); an icon set belongs to a source of
# tools/icon-sources.conf (e.g. Papirus-Dark from papirus, Tela-nord from tela). Without a name, install/remove/switch ask.
# Workflow: install-theme copies from this checkout; update-theme does git fetch + pull --ff-only first. Icons: clone the
# source into the cache when missing, else bring it to the latest upstream (install and update both), then replace each
# set's folder in the destination (remove it, copy the fresh one; unrelated folders there are never touched).
# Collision guard: every folder this script installs gets a marker file (.gnome-themes, containing the scheme/set name). A
# folder is replaced or removed only when it carries the marker or, for installs from before the marker existed, when its
# index.theme is byte-identical to the one of our source. Any other folder of the same name (e.g. a third-party Dracula) is
# never replaced silently: in a terminal the script asks (default no), without one it refuses that folder with a message and
# carries on with the others; FORCE=1 in the environment overrides the guard.
# Themes have a per-scheme accent (one of the scheme's accents, the six terminal colours plus orange where it has one, listed in <scheme>/accents/list): switch asks for it
# (or takes it as the 4th argument), remembers it in $XDG_STATE_HOME/gnome-themes/accents (lines scheme=accent), and
# install/update re-apply the remembered one by running the scheme's sed token map over the installed copies.
# Terminal palette: every scheme uses a Ptyxis BUILT-IN palette, declared by ID in its scheme.toml: `ptyxis = "<id>"` and, for a scheme whose
# light variant is a separate flat built-in, `ptyxis_light = "<id>"`. Ptyxis keys a profile's `palette` setting by palette id (the resource file
# name without `.palette`, case-sensitive, e.g. 'nord', 'Catppuccin Mocha'), never by the display Name; an unknown value makes Ptyxis fall back
# silently to its default palette. Nothing is copied or installed for the terminal. switch sets the id as the `palette` of the default Ptyxis
# profile and of every profile that already has a palette key (other profiles are left alone) through dconf, picks `ptyxis_light` instead of
# `ptyxis` when the system colour scheme is light, reads the key back and warns when the id is not a built-in of the installed Ptyxis;
# without dconf, or before Ptyxis has created a profile, it says so and skips. The accent does not change the palette. Earlier versions
# installed generated palette files (gnome-themes-*.palette with the marker line `# gnome-themes: <scheme>`) into PTYXIS_PALETTES; install,
# update, switch and remove delete files that carry that marker (one line per file) and never a file without it.
# GtkSourceView: every scheme also has editor style schemes (<scheme>/gtksourceview/gnome-themes-<scheme>-{dark,light}.xml, generated by
# tools/gtksourceview-gen.py). They are copied (marker comment `<!-- gnome-themes: <scheme> -->`, same collision rules) into
# GTKSOURCEVIEW_STYLES (~/.local/share/gtksourceview-5/styles) and, because a Flatpak app looks only in its own data directory, also into
# $FLATPAK_APPS/<id>/data/gtksourceview-5/styles (FLATPAK_APPS = ~/.var/app) for org.gnome.TextEditor and org.gnome.Builder when that app is
# installed. switch sets the Text Editor key /org/gnome/TextEditor/style-scheme (the -dark id while the desktop is dark, else -light when the
# scheme has one) and, only when Builder exists (schema or Flatpak), /org/gnome/builder/editor/style-scheme-name.
# Flatpak access: Flatpak apps see neither ~/.config/gtk-3.0|4.0, ~/.themes nor ~/.local/share/icons unless allowed (the list is fp_paths below,
# read-only). After a switch, when `flatpak` exists and the global user override lacks any of them, the script asks (default no; without a
# terminal it prints the exact command) and only on y runs `flatpak override --user --filesystem=...` for the MISSING entries and records
# exactly those in $XDG_STATE_HOME/gnome-themes/flatpak-overrides; an entry that existed before is never recorded and never removed. When
# remove-theme or remove-icon removes the last installed theme and icon set of this repo's (those with the marker) and the record lists
# entries, it asks (default no; without a terminal it prints the commands) and on y runs `--nofilesystem=` for the recorded entries only.
# GtkSourceView schemes need no entry: Flatpak apps read their own ~/.var/app/<id>/data (see the styles section).
# Environment: THEMES_DEST (~/.themes), ICONS_DEST (~/.local/share/icons), ICONS_URL (replaces the papirus source's URL),
# ICON_SOURCES (another registry file), GNOME_THEMES_CACHE (~/.cache/gnome-themes; icon clones in icons/<source>),
# PTYXIS_PALETTES (~/.local/share/org.gnome.Ptyxis/palettes),
# GTKSOURCEVIEW_STYLES, FLATPAK_APPS,
# FORCE=1 (replace or remove folders that were not installed by gnome-themes without asking).
set -euo pipefail

# the guard asks on a copy of the original stdin (fd 3): the loops below read their own input from process substitutions
tty_in=0; if [ -t 0 ]; then tty_in=1; exec 3<&0; fi
kind="${1:-}"; action="${2:-}"; want="${3:-}"; accent_arg="${4:-}"
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cache="${GNOME_THEMES_CACHE:-${XDG_CACHE_HOME:-$HOME/.cache}/gnome-themes}"
cfg="${XDG_CONFIG_HOME:-$HOME/.config}"
state="${XDG_STATE_HOME:-$HOME/.local/state}/gnome-themes"
gsv_dir="${GTKSOURCEVIEW_STYLES:-${XDG_DATA_HOME:-$HOME/.local/share}/gtksourceview-5/styles}"
fp_apps="${FLATPAK_APPS:-$HOME/.var/app}"
pty_dir="${PTYXIS_PALETTES:-${XDG_DATA_HOME:-$HOME/.local/share}/org.gnome.Ptyxis/palettes}"
case "$kind" in
    themes) dest="${THEMES_DEST:-$HOME/.themes}"; noun="theme" ;;
    icons)  dest="${ICONS_DEST:-${XDG_DATA_HOME:-$HOME/.local/share}/icons}"; noun="icon set" ;;
    *) echo "usage: themectl.sh <themes|icons> <install|list|update|remove|switch> [name] [accent]"; exit 2 ;;
esac

# ---- accents (themes only) -----------------------------------------------------------------------------------
# state file lines: key=value
state_get() { [ -f "$1" ] && sed -n "s/^$2=//p" "$1" | head -n1 || true; }
state_set() { mkdir -p "$(dirname "$1")"; { [ -f "$1" ] && grep -v "^$2=" "$1" || true; echo "$2=$3"; } > "$1.new"; mv "$1.new" "$1"; }
state_del() { [ -f "$1" ] || return 0; { grep -v "^$2=" "$1" || true; } > "$1.new"; mv "$1.new" "$1"; }
acc_names=(); acc_dark=(); acc_light=(); acc_default=""
load_accents() {   # accents of scheme $1 from <scheme>/accents/list (name dark light|- [default])
    acc_names=(); acc_dark=(); acc_light=(); acc_default=""
    local n d l f
    [ -f "$root/$1/accents/list" ] || return 0
    while read -r n d l f; do
        case "$n" in ""|"#"*) continue ;; esac
        acc_names+=("$n"); acc_dark+=("$d"); acc_light+=("$l"); if [ "$f" = default ]; then acc_default="$n"; fi
    done < "$root/$1/accents/list"
}
current_accent() { local a; a=$(state_get "$state/accents" "$1"); load_accents "$1"; [ -n "$a" ] && printf '%s\n' "${acc_names[@]}" | grep -qx "$a" && echo "$a" || echo "$acc_default"; }
accent_maps() {    # sets map_dark, map_light for scheme $1 accent $2 (light falls back to dark for dark-only schemes)
    map_dark="$root/$1/accents/$2.dark.sed"; map_light="$root/$1/accents/$2.light.sed"
    [ -f "$map_light" ] || map_light="$map_dark"
}
apply_accent() {   # apply_accent SCHEME ACCENT [FOLDER]: run the token maps over the installed copies of SCHEME
    local sc="$1" a="$2" f d
    load_accents "$sc"; [ -n "$a" ] && [ "$a" != "$acc_default" ] || return 0
    accent_maps "$sc" "$a"
    [ -f "$map_dark" ] || { echo "No accent map for $sc/$a" >&2; return 1; }
    while read -r f; do
        d="$dest/$f"
        case "$f" in
            *-Shell-Dark)  sed -i -f "$map_dark" "$d/gnome-shell/gnome-shell.css" ;;
            *-Shell-Light) sed -i -f "$map_light" "$d/gnome-shell/gnome-shell.css" ;;
            *-Shell-*) ;;
            *) for v in gtk-3.0 gtk-4.0; do
                   [ -f "$d/$v/gtk.css" ] && sed -i -f "$map_light" "$d/$v/gtk.css"
                   [ -f "$d/$v/gtk-dark.css" ] && sed -i -f "$map_dark" "$d/$v/gtk-dark.css"
               done ;;
        esac
    done < <(if [ -n "${3:-}" ]; then echo "$3"; else folders_of "$sc"; fi)
}
accent_label() {   # label of accent index $1: name, hex (dark / light)
    local l="${acc_names[$1]}  ${acc_dark[$1]}"; [ "${acc_light[$1]}" != "-" ] && l="$l / ${acc_light[$1]}"; echo "$l"
}
# choose_accent SCHEME: sets accent_pick (the name) from the scheme's accents; Enter/cancel keeps the current one
accent_pick=""
choose_accent() {
    local sc="$1" cur i a ls=()
    cur=$(current_accent "$sc"); accent_pick="$cur"; load_accents "$sc"
    [ "${#acc_names[@]}" -gt 0 ] || { accent_pick=""; return 0; }
    for i in "${!acc_names[@]}"; do
        l=$(accent_label "$i"); if [ "${acc_names[i]}" = "$cur" ]; then l="$l  (current)"; fi; ls+=("$l")
    done
    local savedl=("${labels[@]}") rc=0 idx=() cc=0
    labels=("${ls[@]}"); for i in "${!ls[@]}"; do idx+=("$i"); if [ "${acc_names[i]}" = "$cur" ]; then cc=$i; fi; done
    tui_cur=$cc; pick=""; tui_one "Accent colour for $sc" "${idx[@]}" || rc=$?; tui_cur=0; labels=("${savedl[@]}")
    if [ "$rc" -eq 0 ] && [ -n "$pick" ]; then accent_pick="${acc_names[pick]}"
    elif [ "$rc" -eq 2 ]; then
        echo; echo "Accent colour for $sc (the scheme's terminal colours):"
        for i in "${!ls[@]}"; do printf ' %2d) %s\n' "$((i+1))" "${ls[i]}"; done
        read -r -p "Number (Enter keeps $cur): " a || a=""
        if [[ "$a" =~ ^[0-9]+$ ]] && [ "$a" -ge 1 ] && [ "$a" -le "${#acc_names[@]}" ]; then accent_pick="${acc_names[$((a-1))]}"; fi
    fi

}

# ---- sources -------------------------------------------------------------------------------------
# Themes are copied straight from the checkout this script lives in (no cache, no network on install).
# Icon sets come from the external repos listed in tools/icon-sources.conf (name|url|layout|extra), each with a
# shallow clone under $cache/icons/<source>. Layouts: top (top-level dirs with index.theme are the sets), root (the
# repo root is the set), script (sets are built by the upstream install.sh, one variant per set, in a temp dir).
# The registry DECLARES every set name (column 4), so listing needs no clone; a source is cloned only when one of its
# sets is installed or updated, and then checked against its declaration (warnings only, see verify_source).
conf="${ICON_SOURCES:-$root/tools/icon-sources.conf}"
src_names=(); declare -A src_url src_layout src_extra
load_sources() {
    local n u l e
    while IFS='|' read -r n u l e; do
        case "$n" in ""|"#"*) continue ;; esac
        src_names+=("$n"); src_url[$n]="$u"; src_layout[$n]="$l"; src_extra[$n]="$e"
    done < "$conf"
    if [ -n "${ICONS_URL:-}" ]; then   # override (testing): replaces the papirus source's URL, adding the source if needed
        if [ -z "${src_url[papirus]:-}" ]; then src_names+=(papirus); src_layout[papirus]=top; src_extra[papirus]=""; fi
        src_url[papirus]="$ICONS_URL"
        [ -n "${src_extra[papirus]}" ] || src_extra[papirus]="Papirus Papirus-Dark Papirus-Light"
    fi
}
clone_of() { echo "$cache/icons/$1"; }
migrate_cache() {  # before 2026-11-07 the single Papirus clone lived at $cache/icons itself
    if [ -d "$cache/icons/.git" ]; then mv "$cache/icons" "$cache/icons.legacy" && mkdir -p "$cache/icons" && mv "$cache/icons.legacy" "$cache/icons/papirus"; fi
}
ensure_clone() {   # clone source $1 when its cache dir is missing
    local d; d=$(clone_of "$1"); [ -d "$d/.git" ] && return 0
    mkdir -p "$cache/icons"; echo "Cloning $1 ..."
    git clone --quiet --depth 1 "${src_url[$1]}" "$d" 2>/dev/null || { rm -rf "${d:?}"; echo "(could not clone $1; skipping it)" >&2; return 1; }
    verify_source "$1"
}
verify_source() {  # compare the clone of source $1 with the sets the registry declares; one warning line per mismatch, never fatal
    local n="$1" d t dir nm dd b seen=" "; d=$(clone_of "$n")
    case "${src_layout[$n]}" in
        top)
            for t in ${src_extra[$n]}; do
                dir="${t%%=*}"; nm="${t#*=}"; seen="$seen$dir "
                if [ ! -f "$d/$dir/index.theme" ] || [ "$(set_name "$d/$dir" "$dir")" != "$nm" ]; then echo "warning: $n: registry says $nm, upstream has no $nm" >&2; fi
            done
            for dd in "$d"/*/; do
                [ -f "$dd/index.theme" ] || continue; b=$(basename "$dd")
                case "$seen" in *" $b "*) ;; *) echo "warning: $n: upstream has $(set_name "$dd" "$b") not in the registry" >&2 ;; esac
            done ;;
        root)
            nm=$(set_name "$d" "${src_extra[$n]}")
            if [ ! -f "$d/index.theme" ] || [ "$nm" != "${src_extra[$n]}" ]; then echo "warning: $n: registry says ${src_extra[$n]}, upstream has no ${src_extra[$n]}" >&2; fi ;;
    esac
    return 0
}
refresh_source() { # bring the shallow clone of source $1 to the latest upstream; offline: keep the cache and say so
    local d; d=$(clone_of "$1")
    if [ -d "$d/.git" ]; then
        if git -C "$d" fetch --quiet --depth 1 origin HEAD 2>/dev/null && git -C "$d" reset --quiet --hard FETCH_HEAD; then verify_source "$1"
        else echo "(could not refresh $1; using the cached copy)"; fi
    else ensure_clone "$1" || true; fi
}
sync_themes() {    # git fetch + pull --ff-only in this checkout; quiet on a detached HEAD or a branch without upstream
    git -C "$root" remote get-url origin >/dev/null 2>&1 || return 0
    git -C "$root" fetch --quiet 2>/dev/null || { echo "(could not fetch; using the checkout as it is)"; return 0; }
    if git -C "$root" symbolic-ref -q HEAD >/dev/null && git -C "$root" rev-parse '@{u}' >/dev/null 2>&1; then
        git -C "$root" pull --quiet --ff-only 2>/dev/null || echo "(could not fast-forward the checkout; using it as it is)"
    fi
}
if [ "$kind" = icons ]; then load_sources; migrate_cache; fi

# Featured themes: listed first (marked with a star) in list-themes and the install/switch/remove checklists, in this order, then every
# other scheme alphabetically. The ONE place to change the favorites; tools/test.sh and CI read the same line (FEATURED_THEMES may be
# set in the environment to override it).
FEATURED_THEMES="${FEATURED_THEMES-nordic gruvbox-material everforest tokyo-night dracula fairy-floss}"

items=(); labels=(); declare -A i_src i_dir i_var
set_name() {       # set name of an icon dir $1: its index.theme Name= when that is a plain id, else $2
    local nm; nm=$(sed -n 's/^Name=//p' "$1/index.theme" 2>/dev/null | head -n1 | tr -d '\r')
    case "$nm" in ""|*[[:space:]/]*) echo "$2" ;; *) echo "$nm" ;; esac
}
add_item() { items+=("$1"); labels+=("$1  ($2)"); i_src[$1]="$2"; i_dir[$1]="$3"; i_var[$1]="$4"; }
load_items() {
    items=(); labels=(); i_src=(); i_dir=(); i_var=()
    if [ "$kind" = themes ]; then
        local all=() ordered=() f seen
        for p in "$root"/*/palette.toml; do
            sc=$(basename "$(dirname "$p")"); [ -d "$root/$sc/themes" ] && all+=("$sc")
        done
        mapfile -t all < <(printf '%s\n' "${all[@]}" | LC_ALL=C sort)
        for f in $FEATURED_THEMES; do for sc in "${all[@]}"; do [ "$sc" = "$f" ] && ordered+=("$sc"); done; done
        for sc in "${all[@]}"; do
            seen=0; for f in $FEATURED_THEMES; do [ "$sc" = "$f" ] && seen=1; done
            [ "$seen" -eq 1 ] || ordered+=("$sc")
        done
        for sc in "${ordered[@]}"; do
            gtk=""; shell=""
            for d in "$root/$sc"/themes/*/; do
                n=$(basename "$d")
                case "$n" in
                    *-Shell-*) v="${n##*-Shell-}"; shell="${shell:+$shell/}$(printf '%s' "$v" | tr 'A-Z' 'a-z')" ;;
                    *) gtk="GTK 3/4" ;;
                esac
            done
            what="${gtk}${gtk:+${shell:+ + }}${shell:+GNOME Shell $shell}"
            star=""; for f in $FEATURED_THEMES; do [ "$sc" = "$f" ] && star="★ "; done
            items+=("$sc"); labels+=("$star$sc  ($what)")
        done
    else
        local n t v base
        for n in "${src_names[@]}"; do   # from the registry only: no clone, no network
            case "${src_layout[$n]}" in
                top) for t in ${src_extra[$n]}; do add_item "${t#*=}" "$n" "${t%%=*}" ""; done ;;
                root) add_item "${src_extra[$n]}" "$n" "" "" ;;
                script) base="${n^}"
                        for v in ${src_extra[$n]}; do
                            if [ "$v" = standard ]; then add_item "$base" "$n" "" "$v"; else add_item "$base-$v" "$n" "" "$v"; fi
                        done ;;
                *) echo "icon-sources.conf: unknown layout '${src_layout[$n]}' for $n" >&2 ;;
            esac
        done
    fi
}
folders_of() {   # installable folder names of item $1 (exactly these: never a glob, so removing Tela keeps Tela-blue)
    if [ "$kind" = themes ]; then for d in "$root/$1"/themes/*/; do basename "$d"; done
    elif [ "${src_layout[${i_src[$1]}]}" = script ]; then echo "$1"; echo "$1-dark"; echo "$1-light"
    else echo "$1"; fi
}
build_dir=""
prepare_item() { # icons, script layout: run the upstream install.sh for the variant into a temp dir (never the real destination)
    [ "$kind" = icons ] || return 0
    [ "${src_layout[${i_src[$1]}]}" = script ] || return 0
    local d f; d=$(clone_of "${i_src[$1]}"); build_dir=$(mktemp -d)
    echo "Building $1 with the upstream install.sh (variant ${i_var[$1]}) ..."
    (cd "$d" && ./install.sh -d "$build_dir" "${i_var[$1]}" >/dev/null 2>&1) || { echo "install.sh failed for $1" >&2; return 1; }
    while read -r f; do [ -d "$build_dir/$f" ] || { echo "install.sh did not produce $f" >&2; return 1; }; done < <(folders_of "$1")
}
shared_bases() {  # hidden base dirs (e.g. .Fluent-base) that the installed folders of item $1 link into
    local f
    while read -r f; do [ -d "$dest/$f" ] && find "$dest/$f" -type l -printf '%l\n' 2>/dev/null; done < <(folders_of "$1") \
        | sed -n 's|^\(\.\./\)\{1,\}\(\.[^/][^/]*\)/.*|\2|p' | sort -u || true
}
finish_item() { if [ -n "$build_dir" ]; then rm -rf "${build_dir:?}"; build_dir=""; fi; }
# ---- collision guard -----------------------------------------------------------------------------
# A folder in $dest is ours when it has the marker file, or (installs from before the marker) when its index.theme is
# byte-identical to the index.theme of our source for that folder (themes: the generated one of the scheme; icons: the
# cloned or freshly built one; script-built sets have no source copy outside install, so they are adopted on install only).
marker=.gnome-themes
src_index() {    # src_index ITEM FOLDER: our source's index.theme for that folder (may not exist)
    if [ "$kind" = themes ]; then echo "$root/$1/themes/$2/index.theme"; return; fi
    case "${src_layout[${i_src[$1]}]}" in
        top)    echo "$(clone_of "${i_src[$1]}")/${i_dir[$1]}/index.theme" ;;
        root)   echo "$(clone_of "${i_src[$1]}")/index.theme" ;;
        script) [ -n "$build_dir" ] && echo "$build_dir/$2/index.theme" || echo "" ;;
    esac
}
is_ours() {      # is_ours DIR SRC_INDEX
    [ -d "$1" ] || return 1
    [ -f "$1/$marker" ] && return 0
    [ -n "${2:-}" ] && [ -f "$2" ] && [ -f "$1/index.theme" ] && cmp -s "$2" "$1/index.theme"
}
# may_touch DIR SRC_INDEX VERB: 0 when DIR is absent, ours, FORCE=1 or the user says yes in a terminal; else 1 (with a message)
may_touch() {
    local d="$1" a
    [ -e "$d" ] || [ -L "$d" ] || return 0
    is_ours "$d" "${2:-}" && return 0
    [ "${FORCE:-}" = 1 ] && return 0
    if [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "$d exists and was not installed by gnome-themes. ${3:-Replace} it? [y/N] " a || a=n
        case "$a" in [yY]*) return 0 ;; esac
        echo "Left $d alone." >&2; return 1
    fi
    echo "Refused: $d exists and was not installed by gnome-themes; left alone (FORCE=1 replaces it, or run in a terminal to be asked)." >&2
    return 1
}
mark_dir() { printf '%s\n' "$2" > "$1/$marker"; }
is_installed() { local f; while read -r f; do [ -e "$dest/$f" ] && is_ours "$dest/$f" "$(src_index "$1" "$f")" && return 0; done < <(folders_of "$1"); return 1; }
index_of() { local i; for i in "${!items[@]}"; do [ "${items[i]}" = "$1" ] && { echo "$i"; return 0; }; done; return 1; }

# ---- prompts -------------------------------------------------------------------------------------
# Terminal UI (no dependencies): up/down or j/k move, SPACE toggles, a all, n none, ENTER confirms, q cancels. Without a
# terminal the numbered lists below are used.
# Terminal checklist for bash: arrow keys or j/k move, SPACE toggles, a = all, n = none, Enter confirms, q cancels.
# No dependencies. Draws on stderr, reads the keyboard from /dev/tty. Needs: labels[] (display text per index),
# on[] (1 = ticked) for tui_many. Returns 2 when there is no terminal, so the caller can fall back to a numbered list.
#   tui_many HEADER IDX...   sets chosen=(ticked indexes among IDX); returns 1 when cancelled
#   tui_one  HEADER IDX...   sets pick=<index> (empty when cancelled); tui_cur=N (position within IDX) puts the cursor there
_tui_read_key() {   # sets key to: up down space enter quit all none or the raw character
    local k rest
    IFS= read -rsn1 k </dev/tty || { key=quit; return; }
    case "$k" in
        $'\e') IFS= read -rsn2 -t 0.05 rest </dev/tty || rest=""
               case "$rest" in '[A'|'OA') key=up ;; '[B'|'OB') key=down ;; *) key=quit ;; esac ;;
        ' ') key=space ;; '') key=enter ;; k) key=up ;; j) key=down ;; a) key=all ;; n) key=none ;; q) key=quit ;;
        *) key="$k" ;;
    esac
}
_tui_end() { stty "$_tui_saved" </dev/tty 2>/dev/null; printf '\e[?25h' >&2; trap - INT; }
_tui_run() {   # _tui_run MODE HEADER IDX... ; MODE many|one
    local mode="$1" header="$2"; shift 2; local cand=("$@") n=$# cur="${tui_cur:-0}" i line first=1
    [ -t 0 ] && [ -t 2 ] && [ -r /dev/tty ] || return 2
    _tui_saved=$(stty -g </dev/tty) || return 2
    trap '_tui_end; exit 130' INT
    stty -echo -icanon min 1 time 0 </dev/tty; printf '\e[?25l' >&2
    local hint="up/down move, SPACE toggles, a all, n none, ENTER confirms, q cancels"
    [ "$mode" = one ] && hint="up/down move, ENTER selects, q cancels"
    while true; do
        [ "$first" -eq 0 ] && printf '\e[%dA' "$((n+1))" >&2
        first=0
        printf '\r\e[K%s (%s)\n' "$header" "$hint" >&2
        for i in "${!cand[@]}"; do
            line="${labels[${cand[i]}]}"
            if [ "$mode" = many ]; then
                local mark=" "; [ "${on[${cand[i]}]:-0}" -eq 1 ] && mark="x"
                line="[$mark] $line"
            fi
            if [ "$i" -eq "$cur" ]; then printf '\r\e[K\e[7m> %s\e[0m\n' "$line" >&2; else printf '\r\e[K  %s\n' "$line" >&2; fi
        done
        _tui_read_key
        case "$key" in
            up) cur=$(( (cur + n - 1) % n )) ;;
            down) cur=$(( (cur + 1) % n )) ;;
            space) [ "$mode" = many ] && on[${cand[cur]}]=$((1 - ${on[${cand[cur]}]:-0})) ;;
            all) [ "$mode" = many ] && for i in "${cand[@]}"; do on[i]=1; done ;;
            none) [ "$mode" = many ] && for i in "${cand[@]}"; do on[i]=0; done ;;
            enter) if [ "$mode" = one ]; then pick="${cand[cur]}"; else chosen=(); for i in "${cand[@]}"; do [ "${on[i]:-0}" -eq 1 ] && chosen+=("$i"); done; fi; _tui_end; return 0 ;;
            quit) if [ "$mode" = one ]; then pick=""; else chosen=(); fi; _tui_end; return 1 ;;
        esac
    done
}
tui_many() { chosen=(); _tui_run many "$@"; }
tui_one()  { pick=""; _tui_run one "$@"; }

# choose_many HEADER IDX... : tick entries from the candidate indexes; sets chosen=(indexes). Preselected = on[]
chosen=(); on=()
choose_many() {
    local header="$1"; shift; local cand=("$@") i a mark rc=0
    chosen=()
    tui_many "$header" "${cand[@]}" || rc=$?
    if [ "$rc" -eq 1 ]; then echo "Cancelled."; exit 0
    elif [ "$rc" -eq 2 ]; then
        while true; do
            echo; echo "$header:"
            for i in "${!cand[@]}"; do
                mark=" "; if [ "${on[${cand[i]}]:-0}" -eq 1 ]; then mark="x"; fi
                printf ' %2d) [%s] %s\n' "$((i+1))" "$mark" "${labels[${cand[i]}]}"
            done
            read -r -p "Number toggles, a = all, n = none, Enter = confirm, q = quit: " a || a=q
            case "$a" in
                "") break ;;
                q) echo "Cancelled."; exit 0 ;;
                a) for i in "${cand[@]}"; do on[i]=1; done ;;
                n) for i in "${cand[@]}"; do on[i]=0; done ;;
                *[!0-9]*) echo "Not a number: $a" ;;
                *) if [ "$a" -ge 1 ] && [ "$a" -le "${#cand[@]}" ]; then i=${cand[$((a-1))]}; on[i]=$((1-${on[i]:-0})); else echo "Out of range: $a"; fi ;;
            esac
        done
        for i in "${cand[@]}"; do if [ "${on[i]:-0}" -eq 1 ]; then chosen+=("$i"); fi; done
    fi
}
# choose_one HEADER IDX... : pick exactly one; sets pick=index (empty when cancelled)
pick=""
choose_one() {
    local header="$1"; shift; local cand=("$@") i a rc=0
    pick=""
    tui_one "$header" "$@" || rc=$?
    if [ "$rc" -eq 2 ]; then
        echo; echo "$header:"
        for i in "${!cand[@]}"; do printf ' %2d) %s\n' "$((i+1))" "${labels[${cand[i]}]}"; done
        read -r -p "Number (Enter cancels): " a || a=""
        if [[ "$a" =~ ^[0-9]+$ ]] && [ "$a" -ge 1 ] && [ "$a" -le "${#cand[@]}" ]; then pick="${cand[$((a-1))]}"; fi
    fi
}

# ---- Ptyxis palettes (themes only) ----------------------------------------------------------------------------
pty_ours() { [ -f "$2" ] && { grep -qxF "# gnome-themes: $1" "$2" || grep -qxF "<!-- gnome-themes: $1 -->" "$2"; }; }   # pty_ours SCHEME FILE (palette or style scheme marker)
# pty_may_touch SCHEME VERB FILE: 0 when the palette file is absent, ours, FORCE=1 or the user says yes in a terminal (same rules as folders)
pty_may_touch() {
    local d a; d="$3"
    [ -e "$d" ] || return 0
    pty_ours "$1" "$d" && return 0
    [ "${FORCE:-}" = 1 ] && return 0
    if [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "$d exists and was not installed by gnome-themes. ${2:-Replace} it? [y/N] " a || a=n
        case "$a" in [yY]*) return 0 ;; esac
        echo "Left $d alone." >&2; return 1
    fi
    echo "Refused: $d exists and was not installed by gnome-themes; left alone (FORCE=1 replaces it, or run in a terminal to be asked)." >&2
    return 1
}
pty_cleanup() {  # delete leftover generated palette files of earlier versions: only files that carry our marker line
    local f; [ -d "$pty_dir" ] || return 0
    for f in "$pty_dir"/*.palette; do
        [ -f "$f" ] && grep -qE '^# gnome-themes: [A-Za-z0-9._-]+[[:space:]]*$' "$f" || continue
        rm -f "$f" && echo "Removed old generated Ptyxis palette $f (Ptyxis built-in palettes are used now)."
    done
}
dq() { grep -o "'[^']*'" | tr -d "'"; }   # the quoted strings of a GVariant text value
pty_toml() {  # pty_toml SCHEME KEY: the top-level string value of KEY in scheme.toml (empty when absent)
    awk -v k="$2" '/^\[/ { exit } index($0, k " = \"") == 1 { v = substr($0, length(k) + 5); sub(/".*$/, "", v); print v; exit }' "$root/$1/scheme.toml" 2>/dev/null | tr -d '\r'
}
pty_mode() {  # dark or light, from the system colour scheme (prefer-dark = dark, prefer-light = light; `default` = dark only when the GTK theme in use is a dark one, else light; no gsettings = dark)
    local cs gt; cs=$(gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | tr -d "'") || cs=""
    case "$cs" in
        prefer-dark) echo dark ;;
        prefer-light) echo light ;;
        default) gt=$(gsettings get org.gnome.desktop.interface gtk-theme 2>/dev/null | tr -d "'") || gt=""
                 case "$gt" in *[Dd]ark*) echo dark ;; *) echo light ;; esac ;;
        *) echo dark ;;
    esac
}
pty_switch() {   # set the palette id on the default profile and on every profile that already has a palette key
    local s="$1" id lt mode uuids u def sel=() done_n=0 got known
    id=$(pty_toml "$s" ptyxis); lt=$(pty_toml "$s" ptyxis_light)
    [ -n "$id" ] || { echo "Ptyxis palette not applied: $s declares no \`ptyxis\` id in its scheme.toml."; return 0; }
    if [ -n "$lt" ] && [ "$lt" != "$id" ]; then
        mode=$(pty_mode)
        if [ "$mode" = light ]; then id="$lt"; fi
        echo "Ptyxis: $s has a separate palette per mode; the system colour scheme reads as $mode, so the palette id is '$id'. Run switch-theme again after changing between light and dark to pick the other one."
    fi
    command -v dconf >/dev/null 2>&1 || { echo "Ptyxis palette not applied: dconf not found. Pick the built-in with id '$id' in Ptyxis > Preferences > Palette."; return 0; }
    uuids=$(dconf read /org/gnome/Ptyxis/profile-uuids 2>/dev/null | dq || true)
    def=$(dconf read /org/gnome/Ptyxis/default-profile-uuid 2>/dev/null | dq | head -n1 || true)
    [ -n "$def" ] || def=$(printf '%s\n' "$uuids" | head -n1)
    if [ -z "$def" ]; then
        echo "Ptyxis palette not applied: no Ptyxis profile found (settings absent; start Ptyxis once, then run switch-theme again, or pick the built-in with id '$id' in Preferences > Palette)."
        return 0
    fi
    sel=("$def")
    for u in $uuids; do
        [ "$u" = "$def" ] && continue
        [ -n "$(dconf read "/org/gnome/Ptyxis/Profiles/$u/palette" 2>/dev/null || true)" ] && sel+=("$u")
    done
    for u in "${sel[@]}"; do
        dconf write "/org/gnome/Ptyxis/Profiles/$u/palette" "'$id'" && done_n=$((done_n+1))
        got=$(dconf read "/org/gnome/Ptyxis/Profiles/$u/palette" 2>/dev/null || true)
        echo "Ptyxis palette key reads $got (profile $u)"
    done
    echo "Ptyxis palette id is now '$id' (Ptyxis built-in) on $done_n profile(s) (the default one, plus those that already had a palette set)."
    if known=$(python3 -I "$root/tools/ptyxis-ids.py" ids 2>/dev/null); then
        printf '%s\n' "$known" | grep -qxF -- "$id" || echo "WARNING: '$id' is not a built-in palette id of the installed Ptyxis; Ptyxis would fall back to its default palette (ids are case-sensitive; see tools/ptyxis-ids.py list)."
    else echo "Note: the Ptyxis binary could not be read, so the id was not checked against its built-in palettes."; fi
}

# ---- GtkSourceView style schemes (themes only) -------------------------------------------------------------------
gsv_apps=(org.gnome.TextEditor org.gnome.Builder)
gsv_app_present() { [ -d "$fp_apps/$1" ] || { command -v flatpak >/dev/null 2>&1 && flatpak info "$1" >/dev/null 2>&1; }; }
gsv_dirs() {   # the styles directories to fill: the user's own, and the data directory of each installed Flatpak editor
    echo "$gsv_dir"; local a; for a in "${gsv_apps[@]}"; do if gsv_app_present "$a"; then echo "$fp_apps/$a/data/gtksourceview-5/styles"; fi; done
}
gsv_files() { local f; for f in "$root/$1"/gtksourceview/*.xml; do [ -f "$f" ] && basename "$f"; done; }   # file names of scheme $1
gsv_install() {  # gsv_install SCHEME: copy the style schemes into every styles directory
    local s="$1" d f n=0
    while read -r d; do
        while read -r f; do
            pty_may_touch "$s" Replace "$d/$f" || continue
            mkdir -p "$d"; cp "$root/$s/gtksourceview/$f" "$d/$f"; n=$((n+1))
        done < <(gsv_files "$s")
    done < <(gsv_dirs)
    if [ "$n" -gt 0 ]; then echo "Installed GtkSource style scheme(s) of $s ($n file(s); editors: $gsv_dir and installed Flatpak editors)."; fi
}
gsv_refresh() {  # update: refresh only the files that exist and are ours
    local s="$1" d f
    while read -r d; do
        while read -r f; do
            [ -f "$d/$f" ] && pty_ours "$s" "$d/$f" && cp "$root/$s/gtksourceview/$f" "$d/$f"
        done < <(gsv_files "$s")
    done < <(gsv_dirs)
    return 0
}
gsv_remove() {
    local s="$1" d f
    while read -r d; do
        while read -r f; do
            [ -e "$d/$f" ] || continue
            pty_may_touch "$s" Remove "$d/$f" || continue
            rm -f "$d/$f"; echo "Removed $d/$f"
        done < <(gsv_files "$s")
    done < <(gsv_dirs)
    return 0
}
gsv_switch() {   # point Text Editor (and Builder when present) at the scheme's style scheme for the current light/dark mode
    local s="$1" id="" dark=1 f
    [ -n "$(gsv_files "$s")" ] || return 0
    [ -f "$gsv_dir/gnome-themes-$s-dark.xml" ] && pty_ours "$s" "$gsv_dir/gnome-themes-$s-dark.xml" || { echo "GtkSource style scheme not applied: the installed copy is missing or not ours."; return 0; }
    gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | grep -qi dark || dark=0
    id="gnome-themes-$s-dark"
    if [ "$dark" = 0 ] && [ -f "$root/$s/gtksourceview/gnome-themes-$s-light.xml" ]; then id="gnome-themes-$s-light"; fi
    command -v dconf >/dev/null 2>&1 || { echo "GtkSource style scheme installed but not applied: dconf not found. Pick \"$id\" in the editor's preferences."; return 0; }
    dconf write /org/gnome/TextEditor/style-scheme "'$id'" && echo "Text Editor style scheme is now $id (Text Editor also recolours its window from it)."
    if gsettings list-schemas 2>/dev/null | grep -qx org.gnome.builder.editor || { command -v flatpak >/dev/null 2>&1 && flatpak info org.gnome.Builder >/dev/null 2>&1; }; then
        dconf write /org/gnome/builder/editor/style-scheme-name "'$id'" && echo "Builder style scheme is now $id."
    else echo "Builder not found (no org.gnome.builder.editor schema, no Flatpak); its style scheme key was not set."; fi
}

# ---- Flatpak access (themes and icons: grant after switch-theme, undo after the last removal) -------------------
# shellcheck disable=SC2088  # the tilde is literal on purpose: flatpak stores and shows the entry as ~/.themes
fp_paths=(xdg-config/gtk-3.0:ro xdg-config/gtk-4.0:ro xdg-data/icons:ro '~/.themes:ro')   # literal tilde, as flatpak stores it; the only entries gnome-themes ever manages
fp_state="$state/flatpak-overrides"
fp_have() { flatpak override --user --show 2>/dev/null | sed -n 's/^filesystems=//p' | tr ';' '\n' | grep -vx '' || true; }
fp_cmd_add() { local c="flatpak override --user" p; for p in "$@"; do c="$c --filesystem=$p"; done; echo "$c"; }
fp_cmd_del() { local c="flatpak override --user" p; for p in "$@"; do c="$c --nofilesystem=${p%:*}"; done; echo "$c"; }
fp_check() {   # after switch-theme: offer the missing read-only entries
    command -v flatpak >/dev/null 2>&1 || return 0
    local have p a miss=()
    have=$(fp_have)
    for p in "${fp_paths[@]}"; do printf '%s\n' "$have" | grep -qxF -- "$p" || miss+=("$p"); done
    [ "${#miss[@]}" -gt 0 ] || return 0
    echo "Flatpak sandbox: no global read-only access yet to: ${miss[*]}"
    if [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "Flatpak apps (for example Calculator, Text Editor) cannot see your themes. Allow read-only access to these folders for all Flatpaks? [y/N] " a || a=n
        case "$a" in
            [yY]*) for p in "${miss[@]}"; do
                       if flatpak override --user --filesystem="$p"; then state_add_line "$fp_state" "$p"; else echo "Could not grant $p." >&2; fi
                   done; echo "Granted; restart the Flatpak apps. gnome-themes removes exactly these again when you remove the last theme and icon set." ;;
            *) echo "Left the Flatpak sandbox alone." ;;
        esac
    else
        echo "Not changing the Flatpak sandbox without a terminal. To allow it, run:"; echo "  $(fp_cmd_add "${miss[@]}")"
        echo "  (or run switch-theme in a terminal and answer y; gnome-themes then records what it added and removes only that later)"
    fi
}
state_add_line() { mkdir -p "$(dirname "$1")"; grep -qxF -- "$2" "$1" 2>/dev/null || echo "$2" >> "$1"; }
any_marked() {   # is any theme or icon set of this repo (marker file) installed? (both destinations, whatever kind runs)
    local d
    for d in "${THEMES_DEST:-$HOME/.themes}" "${ICONS_DEST:-${XDG_DATA_HOME:-$HOME/.local/share}/icons}"; do
        [ -d "$d" ] && find "$d" -mindepth 2 -maxdepth 2 -name "$marker" 2>/dev/null | grep -q . && return 0
    done
    return 1
}
fp_undo() {    # after remove: when nothing of ours is installed any more, offer to remove the recorded entries
    [ -s "$fp_state" ] || return 0
    any_marked && return 0
    local ents=() p a; while read -r p; do [ -n "$p" ] && ents+=("$p"); done < "$fp_state"
    [ "${#ents[@]}" -gt 0 ] || return 0
    if ! command -v flatpak >/dev/null 2>&1; then echo "Flatpak not found; the record $fp_state still lists: ${ents[*]}"; return 0; fi
    if [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "Remove the Flatpak read access that gnome-themes added? [y/N] " a || a=n
        case "$a" in
            [yY]*) for p in "${ents[@]}"; do flatpak override --user --nofilesystem="${p%:*}" || echo "Could not remove $p." >&2; done
                   rm -f "$fp_state"; echo "Removed the Flatpak access gnome-themes had added (${ents[*]})." ;;
            *) echo "Left the Flatpak access in place." ;;
        esac
    else
        echo "gnome-themes added Flatpak read access that nothing uses any more. To remove exactly that, run:"; echo "  $(fp_cmd_del "${ents[@]}")"
        echo "  (then delete $fp_state, or run remove-theme in a terminal and answer y)"
    fi
}

# ---- actions -------------------------------------------------------------------------------------
skipped=(); installed_n=0
was_skipped() { local s; for s in "${skipped[@]}"; do [ "$s" = "$1" ] && return 0; done; return 1; }
copy_folder() {  # replace folder $1 of item $2 in dest: remove the set's folder, then copy the fresh one (never merge); 1 = guard said no
    local f="$1" it="$2" c
    mkdir -p "$dest"
    if ! may_touch "$dest/$f" "$(src_index "$it" "$f")" Replace; then skipped+=("$f"); return 1; fi
    rm -rf "${dest:?}/$f"
    if [ "$kind" = themes ]; then cp -a "$root/$it/themes/$f" "$dest/$f"
    else
        c=$(clone_of "${i_src[$it]}")
        case "${src_layout[${i_src[$it]}]}" in
            top) cp -a "$c/${i_dir[$it]}" "$dest/$f" ;;
            root) mkdir -p "$dest/$f"; (cd "$c" && tar cf - --exclude=./.git --exclude=./.github --exclude=./preview --exclude='./README*' --exclude='./LICENSE*' .) | tar xf - -C "$dest/$f" ;;
            script) cp -a "$build_dir/$f" "$dest/$f" ;;
        esac
        gtk-update-icon-cache -q -f -t "$dest/$f" 2>/dev/null || true
    fi
    mark_dir "$dest/$f" "$it"
    if [ "$kind" = themes ]; then apply_accent "$it" "$(current_accent "$it")" "$f"; fi
    installed_n=$((installed_n+1)); echo "Installed $f -> $dest/$f"
}
copy_item() {
    local f h b mine=0
    prepare_item "$1" || return 1
    while read -r f; do if is_ours "$dest/$f" "$(src_index "$1" "$f")"; then mine=1; fi; done < <(folders_of "$1")
    while read -r f; do copy_folder "$f" "$1" || true; done < <(folders_of "$1")
    if [ -n "$build_dir" ]; then   # hidden shared bases the build produced (Fluent's .Fluent-base ...): replaced too
        for h in "$build_dir"/.[!.]*; do
            [ -d "$h" ] || continue; b=$(basename "$h")
            # a base is ours when marked, or when one of this set's own folders was ours before this run (it links into the base)
            if [ -e "$dest/$b" ] && [ ! -f "$dest/$b/$marker" ] && [ "$mine" -eq 1 ]; then rm -rf "${dest:?}/$b"
            elif ! may_touch "$dest/$b" "" Replace; then continue; else rm -rf "${dest:?}/$b"; fi
            cp -a "$h" "$dest/$b"; mark_dir "$dest/$b" "$1"; echo "Installed $b (shared base)"
        done
    fi
    finish_item
}
refresh_for() {  # icons: refresh the clones of the sources of the named sets ($@)
    local n seen=" "
    for n in "$@"; do case "$seen" in *" ${i_src[$n]} "*) ;; *) seen="$seen${i_src[$n]} "; refresh_source "${i_src[$n]}" ;; esac; done
}
current_value() {  # the value the desktop currently uses (theme or icon set)
    if [ "$kind" = themes ]; then gsettings get org.gnome.desktop.interface gtk-theme 2>/dev/null | tr -d "'" || true
    else gsettings get org.gnome.desktop.interface icon-theme 2>/dev/null | tr -d "'" || true; fi
}
# resolve $want to an index, or explain
resolve() { index_of "$want" || { echo "'$want' is not a $noun here. Available: ${items[*]}" >&2; exit 1; }; }

case "$action" in
    list)
        load_items
        for i in "${!items[@]}"; do
            ac=""; if [ "$kind" = themes ]; then ac="  [accent: $(current_accent "${items[i]}")]"; fi
            if is_installed "${items[i]}"; then echo "✓ ${labels[i]}$ac"; else echo "  ${labels[i]}"; fi
        done ;;

    install)
        load_items
        [ "${#items[@]}" -gt 0 ] || { echo "No ${noun}s found"; exit 1; }
        if [ -n "$want" ]; then
            i=$(resolve); chosen=("$i")
        else
            # themes: every box starts off; icons: installed sets ticked, else Papirus
            for i in "${!items[@]}"; do on[i]=0; done
            if [ "$kind" = icons ]; then
                any=0; for i in "${!items[@]}"; do if is_installed "${items[i]}"; then on[i]=1; any=1; fi; done
                if [ "$any" -eq 0 ]; then for i in "${!items[@]}"; do case "${items[i]}" in Papirus|Papirus-Dark) on[i]=1 ;; esac; done; fi
            fi
            if [ "$kind" = icons ]; then for i in "${!items[@]}"; do if [ "${on[i]}" -eq 1 ] && is_installed "${items[i]}"; then labels[i]="✓ ${labels[i]}"; fi; done; fi
            choose_many "${noun^}s to install into $dest" "${!items[@]}"
        fi
        [ "${#chosen[@]}" -gt 0 ] || { echo "Nothing selected (in the checklist, x ticks an entry and enter installs the ticked ones)."; exit 0; }
        names=(); for i in "${chosen[@]}"; do names+=("${items[i]}"); done
        if [ "$kind" = icons ]; then refresh_for "${names[@]}"; fi   # icons: clone or refresh only the sources of the chosen sets
        for nm in "${names[@]}"; do
            if [ "$kind" = icons ] && [ ! -d "$(clone_of "${i_src[$nm]}")/.git" ]; then echo "Skipping $nm: its source ${i_src[$nm]} is not available." >&2; continue; fi
            copy_item "$nm"; if [ "$kind" = themes ]; then pty_cleanup; gsv_install "$nm"; fi; done
        if [ "$installed_n" -eq 0 ]; then echo "Nothing was installed (see the messages above)."
        elif [ "$kind" = themes ]; then echo "Next: run switch-theme to use it."; else echo "Next: run switch-icon to use it."; fi ;;

    update)
        # themes: git fetch + pull --ff-only in this checkout; icons: refresh the clones of the installed sets' sources.
        # Then every installed set's folders are removed and copied fresh (the remembered accent is re-applied).
        load_items; n=0; inst=()
        for i in "${!items[@]}"; do if is_installed "${items[i]}"; then inst+=("${items[i]}"); fi; done
        if [ "$kind" = icons ]; then refresh_for "${inst[@]}"; else sync_themes; fi
        for nm in "${inst[@]}"; do
            if [ "$kind" = icons ] && [ ! -d "$(clone_of "${i_src[$nm]}")/.git" ]; then echo "Skipping $nm: its source ${i_src[$nm]} is not available." >&2; continue; fi
            if [ "$kind" = icons ]; then copy_item "$nm"; n=$((n+1))
            else while read -r f; do if [ -e "$dest/$f" ] && copy_folder "$f" "$nm"; then n=$((n+1)); fi; done < <(folders_of "$nm"); pty_cleanup; gsv_refresh "$nm"; fi
        done
        [ "$n" -gt 0 ] || echo "None of the ${noun}s from this source is installed in $dest." ;;

    remove)
        load_items; inst=()
        for i in "${!items[@]}"; do if is_installed "${items[i]}"; then inst+=("$i"); fi; done
        [ "${#inst[@]}" -gt 0 ] || { echo "No ${noun}s from this source are installed in $dest."; exit 0; }
        if [ -n "$want" ]; then
            i=$(resolve); is_installed "${items[i]}" || { echo "'$want' is not installed."; exit 1; }
            chosen=("$i")
        else
            for i in "${!items[@]}"; do on[i]=0; done
            choose_many "${noun^}s to remove from $dest" "${inst[@]}"
        fi
        [ "${#chosen[@]}" -gt 0 ] || { echo "Nothing selected."; exit 0; }
        cur=$(current_value); bases=""
        if [ "$kind" = icons ]; then for i in "${chosen[@]}"; do bases+=$'\n'"$(shared_bases "${items[i]}")"; done; fi
        for i in "${chosen[@]}"; do
            while read -r f; do
                if [ -e "$dest/$f" ] || [ -L "$dest/$f" ]; then
                    may_touch "$dest/$f" "$(src_index "${items[i]}" "$f")" Remove || continue
                    rm -rf "${dest:?}/$f"; echo "Removed $dest/$f"
                    if [ "$f" = "$cur" ]; then echo "  note: $f is the one currently in use; run switch to choose another."; fi
                fi
            done < <(folders_of "${items[i]}")
            if [ "$kind" = themes ] && ! is_installed "${items[i]}"; then state_del "$state/accents" "${items[i]}"; fi
            if [ "$kind" = themes ]; then pty_cleanup; gsv_remove "${items[i]}"; fi
        done
        # shared hidden base dirs (Fluent): remove one only when no remaining installed set links into it
        if [ "$kind" = icons ]; then
            still=""; for i in "${!items[@]}"; do if is_installed "${items[i]}"; then still+=$'\n'"$(shared_bases "${items[i]}")"; fi; done
            for b in $bases; do
                if ! printf '%s\n' "$still" | grep -qxF -- "$b" && [ -d "$dest/$b" ] && may_touch "$dest/$b" "" Remove; then rm -rf "${dest:?}/$b"; echo "Removed $dest/$b (shared base, no longer used)"; fi
            done
        fi
        fp_undo ;;

    switch)
        load_items; inst=()
        for i in "${!items[@]}"; do if is_installed "${items[i]}"; then inst+=("$i"); fi; done
        [ "${#inst[@]}" -gt 0 ] || { echo "No ${noun}s from this source are installed; install one first."; exit 1; }
        if [ -n "$want" ]; then
            i=$(resolve); is_installed "${items[i]}" || { echo "'$want' is not installed; install it first."; exit 1; }
        else
            choose_one "Switch to which $noun?" "${inst[@]}"; i="$pick"
            [ -n "$i" ] || { echo "Cancelled."; exit 0; }
        fi
        if [ "$kind" = themes ]; then
            # accent: argument, else the submenu; copy the scheme's folders afresh (clean) and re-apply it
            load_accents "${items[i]}"
            if [ -n "$accent_arg" ]; then
                printf '%s\n' "${acc_names[@]}" | grep -qx "$accent_arg" || { echo "'$accent_arg' is not an accent of ${items[i]}. Available: ${acc_names[*]}" >&2; exit 1; }
                accent_pick="$accent_arg"
            else choose_accent "${items[i]}"; fi
            if [ -n "$accent_pick" ]; then state_set "$state/accents" "${items[i]}" "$accent_pick"; fi
            copy_item "${items[i]}"; pty_cleanup; gsv_install "${items[i]}"
            [ -z "$accent_pick" ] || echo "Accent: $accent_pick."
        fi
        set_ini() {  # set_ini KEY VALUE: rewrite the key in the GTK settings.ini files that already have it
            local f; for f in "$cfg/gtk-3.0/settings.ini" "$cfg/gtk-4.0/settings.ini"; do
                if [ -f "$f" ] && grep -q "^$1=" "$f"; then sed -i "s|^$1=.*|$1=$2|" "$f"; fi
            done
        }
        if [ "$kind" = icons ]; then
            gsettings set org.gnome.desktop.interface icon-theme "${items[i]}"
            set_ini gtk-icon-theme-name "${items[i]}"
            echo "Icon theme is now ${items[i]}."
        else
            sc="${items[i]}"; gtk=""; shell_d=""; shell_l=""
            while read -r f; do
                case "$f" in
                    *-Shell-Dark) shell_d="$f" ;;
                    *-Shell-Light) shell_l="$f" ;;
                    *-Shell-*) ;;
                    *) [ -n "$gtk" ] || gtk="$f" ;;
                esac
            done < <(folders_of "$sc")
            if [ -n "$gtk" ] && was_skipped "$gtk"; then echo "Not switching the GTK theme: $gtk was left alone (not installed by gnome-themes)."; gtk=""; fi
            if [ -n "$gtk" ]; then
                gsettings set org.gnome.desktop.interface gtk-theme "$gtk"; set_ini gtk-theme-name "$gtk"
                echo "GTK theme is now $gtk."
            fi
            shell="$shell_d"
            if ! gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | grep -qi dark; then shell="${shell_l:-$shell_d}"; fi
            if [ -n "$shell" ] && was_skipped "$shell"; then echo "Not switching the Shell theme: $shell was left alone (not installed by gnome-themes)."; shell=""; fi
            if [ -n "$shell" ]; then
                shell_done=0
                if gsettings list-schemas 2>/dev/null | grep -qx org.gnome.shell.extensions.user-theme; then
                    gsettings set org.gnome.shell.extensions.user-theme name "$shell" && shell_done=1
                elif command -v dconf >/dev/null 2>&1; then
                    # The User Themes extension is normally installed per user, so its schema is not in the system schema dirs and
                    # gsettings does not list it: write the key directly.
                    dconf write /org/gnome/shell/extensions/user-theme/name "'$shell'" && shell_done=1
                fi
                if [ "$shell_done" -eq 1 ]; then echo "Shell theme is now $shell (reload it by logging out and in, or toggling the User Themes extension)."
                else echo "Could not set the Shell theme: neither gsettings nor dconf could write the User Themes key."; fi
                if command -v gnome-extensions >/dev/null 2>&1 && ! gnome-extensions list --enabled 2>/dev/null | grep -q '^user-theme@'; then
                    echo "  note: the User Themes extension is not enabled; the Shell theme only applies once it is."
                fi
            fi
            # libadwaita apps ignore the GTK theme and read only the user stylesheet
            la="$root/$sc/libadwaita/gtk.css"; target="$cfg/gtk-4.0/gtk.css"
            if [ -f "$la" ]; then
                ac=$(current_accent "$sc")
                if [ -n "$ac" ] && [ "$ac" != "$acc_default" ]; then
                    accent_maps "$sc" "$ac"; tmpla=$(mktemp); trap 'rm -f "$tmpla"' EXIT
                    if [ "$map_light" = "$map_dark" ]; then sed -f "$map_dark" "$la" > "$tmpla"; else sed -f "$map_light" -f "$map_dark" "$la" > "$tmpla"; fi
                    chmod 644 "$tmpla"; la="$tmpla"
                fi
                mkdir -p "$(dirname "$target")"
                if [ ! -e "$target" ]; then cp "$la" "$target"; echo "Installed $target (libadwaita apps)."
                elif cmp -s "$la" "$target"; then echo "$target is already current."
                elif grep -q "libadwaita-gen.py" "$target" 2>/dev/null || [ -e "$target.bak" ]; then
                    # A file generated by gnome-themes earlier (another accent or scheme), or a backup of the original already exists
                    # (so this file was put here by these recipes): replace it without asking and keep the existing backup.
                    cp "$la" "$target"; echo "Updated $target (libadwaita apps)."
                elif [ -t 0 ]; then
                    read -r -p "$target differs from the scheme's libadwaita file. Replace it (the old one is kept as .bak)? [y/N] " a || a=n
                    case "$a" in [yY]*) cp -L --backup=numbered "$target" "$target.bak"; cp "$la" "$target"; echo "Replaced $target (old one: $target.bak)." ;; *) echo "Left $target alone." ;; esac
                else echo "$target differs from the scheme's libadwaita file; left alone (run in a terminal to replace it)."
                fi
            fi
            pty_cleanup; pty_switch "$sc"; gsv_switch "$sc"; fp_check
            echo "Restart GTK apps to pick up the new theme."
        fi ;;

    *) echo "usage: themectl.sh <themes|icons> <install|list|update|remove|switch> [name] [accent]"; exit 2 ;;
esac
