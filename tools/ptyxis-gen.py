"""Generate a scheme's Ptyxis palette (<scheme>/ptyxis/gnome-themes-<scheme>.palette) from its scheme.toml.

  python3 -I tools/ptyxis-gen.py <scheme-dir> [--check]     # --check: print, write nothing

Only for schemes that declare `ptyxis = "generated"` in scheme.toml (with `ptyxis_reason`). A scheme that declares `ptyxis = "<built-in name>"`
uses that Ptyxis built-in palette (tools/ptyxis-compare.py decides which schemes may, its header has the rules): nothing is written for it, and a
stale generated palette file of that scheme is removed (a file only counts as ours when it ends with the marker line).

Format: the INI file Ptyxis reads from ~/.local/share/org.gnome.Ptyxis/palettes/ that follows the system colour scheme:
[Palette] Name=..., then [Light] and [Dark], each with Foreground, Background, TitlebarBackground, TitlebarForeground,
Cursor and Color0..Color15. The palette Name is "<title> (GNOME Themes)" so it never clashes with a Ptyxis built-in
(Gruvbox Material, Dracula, Fairy Floss ... exist there); the file name is gnome-themes-<scheme>.palette (never clashes
with a hand-made file either). The last line is the marker `# gnome-themes: <scheme>` (the installer's collision guard).

Rules, per slot (a slot takes the scheme's variant of the same name; a dark-only scheme fills [Light] from its dark
variant, as the GTK light slot does). Roles come from scheme.toml (derived ones filled in by palette-from-scheme.py).
An optional table [<variant>.terminal] overrides any of the keys below; every override and its source are recorded in
scheme.toml next to it.
  Foreground          terminal.foreground, else the role `fg`
  Background          terminal.background, else `bg_deep` (the view colour)
  Cursor              terminal.cursor, else Foreground
  TitlebarBackground  terminal.titlebar_background, else the libadwaita headerbar colour: dark `surface`, light `bg_deep`
  TitlebarForeground  terminal.titlebar_foreground, else `fg`
  Color0 (black)      terminal.black, else the scheme's Ptyxis built-in Color0 where the built-in matches the scheme's
                      accents (recorded in scheme.toml as terminal.black), else the role `surface`
  Color1..6           [<variant>.ansi] red green yellow blue magenta cyan
  Color7 (white)      terminal.white, else Foreground
  Color8 (bright black) terminal.bright_black, else the role `comment`
  Color9..14          terminal.bright_red .. bright_cyan, else the normal colour (real brights only where the scheme or
                      its Ptyxis built-in palette has them, `strings -a /usr/bin/ptyxis | grep -A24 '^Name=<Scheme>$'`)
  Color15             terminal.bright_white, else Color7
Foreground on Background must have contrast >= 4.5:1, else the generator stops. The accent chosen with switch-theme does
not change the palette.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # python3 -I does not add the script dir
import schemeroles as sr

NAMES = ('red', 'green', 'yellow', 'blue', 'magenta', 'cyan')

def slot_colors(S, roles, variant):
    R, T = roles[variant], S[variant].get('terminal', {})
    A = S[variant]['ansi']
    c = {}
    fg = T.get('foreground', R['fg']); c['Foreground'] = fg
    c['Background'] = T.get('background', R['bg_deep'])
    c['Cursor'] = T.get('cursor', fg)
    c['TitlebarBackground'] = T.get('titlebar_background', R['surface'] if variant == 'dark' else R['bg_deep'])
    c['TitlebarForeground'] = T.get('titlebar_foreground', R['fg'])
    c['Color0'] = T.get('black', R['surface'])
    for i, n in enumerate(NAMES):
        c['Color%d' % (i + 1)] = A[n]
        c['Color%d' % (i + 9)] = T.get('bright_' + n, A[n])
    c['Color7'] = T.get('white', fg)
    c['Color8'] = T.get('bright_black', R['comment'])
    c['Color15'] = T.get('bright_white', c['Color7'])
    return {k: v.upper() for k, v in c.items()}

ORDER = ['Foreground', 'Background', 'TitlebarBackground', 'TitlebarForeground', 'Cursor'] + ['Color%d' % i for i in range(16)]

def build(scheme_dir):
    S, roles, slots = sr.load(scheme_dir)
    scheme = os.path.basename(os.path.abspath(scheme_dir))
    L = ['[Palette]', 'Name=%s (GNOME Themes)' % S['title'], '']
    for slot, variant in slots:
        c = slot_colors(S, roles, variant)
        cr = sr.contrast(c['Foreground'], c['Background'])
        if cr < 4.5: sys.exit('%s %s: Foreground %s on Background %s has contrast %.2f < 4.5' % (scheme, slot, c['Foreground'], c['Background'], cr))
        L.append('[%s]' % slot.capitalize())
        L += ['%s=%s' % (k, c[k]) for k in ORDER]
        L.append('')
    L += ['# Generated by tools/ptyxis-gen.py from %s/scheme.toml (rules in the script header); do not edit.' % scheme,
          '# gnome-themes: %s' % scheme]
    return scheme, '\n'.join(L) + '\n'

def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    d = sys.argv[1].rstrip('/')
    S, _, _ = sr.load(d)
    scheme = os.path.basename(os.path.abspath(d))
    out = '%s/ptyxis/gnome-themes-%s.palette' % (d, scheme)
    builtin = sr.ptyxis_choice(S)
    if builtin is not None:
        if '--check' not in sys.argv and os.path.isfile(out) and open(out).read().rstrip().endswith('# gnome-themes: ' + scheme):
            os.remove(out)
            try: os.rmdir(os.path.dirname(out))
            except OSError: pass
            print('removed stale generated palette ' + out)
        print('%s: uses the Ptyxis built-in palette "%s"; no palette generated' % (scheme, builtin)); return
    scheme, text = build(d)
    if '--check' in sys.argv: print(text); return
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as f: f.write(text)
    print('wrote ' + out)

if __name__ == '__main__': main()
