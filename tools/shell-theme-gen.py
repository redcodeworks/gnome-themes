"""Generate a scheme's GNOME Shell themes from GNOME Shell's own stock stylesheets.

The stock theme (/usr/share/gnome-shell/gnome-shell-theme.gresource: gnome-shell-dark.css,
gnome-shell-light.css, pad-osd.css) is taken VERBATIM and only COLOUR VALUES are replaced
(selectors, geometry, fonts, transitions, st-mix()/st-lighten()/st-transparentize() calls,
-st-accent-color references and url() references untouched). St's CSS engine accepts only
literals (no @define-color, no relative colours), which is why the stock file is recoloured in
place rather than overridden. The recolour engine is shared with the GTK generators
(tools/themegen.py); the Shell uses the [shell.*] tables of the scheme's palette.toml.

  python3 -I tools/shell-theme-gen.py --palette=gruvbox-material/palette.toml \
      --out=gruvbox-material/themes          # (just generate gruvbox-material)
  add --check to print stats and write nothing.

Writes <out>/<shell_name>-{Dark,Light}/{index.theme,gnome-shell/{gnome-shell.css,pad-osd.css}}.
The stock CSS refers to its SVGs with absolute resource:/// URLs, so the SVGs are loaded from
Shell's own gresource and are not copied. pad-osd.css is copied unmodified. Needs python3-gobject
and gnome-shell installed (to read the gresource).
"""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # python3 -I does not add the script dir
from themegen import arg, load_palette, load_meta, recolour, hx, with_accent, accent_dir_write
import gi
from gi.repository import Gio

if not arg('out'): sys.exit('usage: shell-theme-gen.py --palette=FILE --out=THEMES_DIR [--accent-dir=DIR] [--check]')
if not arg('palette'): sys.exit('--palette=FILE is required')
OUT = os.path.abspath(arg('out'))
PAL = load_palette(arg('palette'), 'shell')
META = load_meta(arg('palette')); NAME = META['shell_name']
GRES = arg('gresource') or '/usr/share/gnome-shell/gnome-shell-theme.gresource'
RES = '/org/gnome/shell/theme/'
res = Gio.Resource.load(GRES)
def stock(name): return bytes(res.lookup_data(RES + name, 0).get_data())

# The stock header comment (licence and copyright) is kept at the top of the generated file.
HDR = '''/* %(title)s GNOME Shell theme, %(variant)s variant.
 * Built on GNOME Shell's OWN stock stylesheet (%(src)s from gnome-shell-theme.gresource,
 * GNOME Shell %(shell)s), taken verbatim and recoloured: ONLY colour values differ from
 * stock; selectors, geometry, fonts, st-*() colour functions and url() references are unchanged.
 * Generated by tools/shell-theme-gen.py from the scheme's palette.toml ([shell.*], derived from its scheme.toml):
 * edit scheme.toml and re-run `just generate`, do not hand-edit this file. A clean-room build: nothing
 * here comes from any third-party Shell theme.
 * Licence: derived from GNOME Shell's stock stylesheet, so LGPL-2.1 (the original header
 * follows unchanged; see LICENSE in this theme folder and NOTICE in the repo). Palette: %(credit)s.
 * Accent: stock Shell reads the accent from the runtime value -st-accent-color / -st-accent-fg-color (GNOME's
 * accent-color setting). St ignores a stylesheet-level `stage { -st-accent-color: ... }` override (tested with St 51.1),
 * so these two keywords are replaced by the scheme's accent and text-on-accent literals, a colour-for-colour
 * substitution at the same positions. The accent is therefore the theme's, not GNOME's accent-color setting; it is
 * switched with `just switch-theme <scheme> <accent>` (sed token maps in <scheme>/accents/).
 */
'''
INDEX = '''[Desktop Entry]
Type=X-GNOME-Metatheme
Name=%s
Comment=%s GNOME Shell theme (%s), stock Shell stylesheet recoloured
Encoding=UTF-8
'''

def shell_version():
    try:
        import subprocess
        return subprocess.run(['gnome-shell', '--version'], capture_output=True, text=True).stdout.split()[-1]
    except Exception: return 'unknown'

def literal_accent(css, P):
    """-st-accent-fg-color / -st-accent-color -> the palette's literals (after recolour: not recoloured again)."""
    css = css.replace('-st-accent-fg-color', P['accent_fg'])
    return css.replace('-st-accent-color', P['fam']['blue'][1])

def build(css, variant, P):
    # Text drawn as translucent white (StEntry text, hint text, other-month calendar days, OSD
    # arrows) would stay neutral white (the engine leaves white alpha overlays alone, which is
    # right for hover/border shades). Text sits on the dark surfaces in both variants, so it
    # becomes the foreground tone at the same alpha: dark fg, light "top" (cream).
    tone = P['fg'] if variant == 'dark' else P['top']
    tr, tg, tb = hx(tone)
    body = recolour(css, P)
    body = re.sub(r'(?m)^(\s*color:\s*)rgba\(255, 255, 255, ([0-9.]+)\)',
                  lambda m: '%srgba(%d, %d, %d, %s)' % (m.group(1), tr, tg, tb, m.group(2)), body)  # after recolour: its output must not be recoloured again
    return literal_accent(body, P)

def main():
    check = '--check' in sys.argv
    ver = shell_version(); adir = arg('accent-dir')
    for variant in PAL:
        src = 'gnome-shell-%s.css' % variant
        css = stock(src).decode()
        hdr = HDR % dict(title=META['title'], variant=variant, src=src, shell=ver, credit=META['credit'])
        new = hdr + build(css, variant, PAL[variant])
        # sanity: St accepts literals only
        assert not re.search(r'hsl\(|@define-color|rgb\(\s*from|var\(|-st-accent', new[len(hdr):]), 'unsupported syntax survived'
        assert new.count('{') == new.count('}'), 'unbalanced braces'
        print(src, len(css), '->', len(new), 'bytes')
        tname = '%s-%s' % (NAME, variant.capitalize())
        if adir:
            for a in PAL[variant]['accents']: accent_dir_write(adir, a, '%s/gnome-shell/gnome-shell.css' % tname, hdr + build(css, variant, with_accent(PAL[variant], a)))
        if check: continue
        d = '%s/%s/gnome-shell' % (OUT, tname)
        os.makedirs(d, exist_ok=True)
        open(d + '/gnome-shell.css', 'w').write(new)
        open(d + '/pad-osd.css', 'wb').write(stock('pad-osd.css'))
        open('%s/%s/index.theme' % (OUT, tname), 'w').write(INDEX % (tname, META['title'], variant))

main()
