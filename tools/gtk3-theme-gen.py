#!/usr/bin/env python3
"""Generate the Gruvbox Material GTK3 theme from GTK3's own built-in Adwaita.

Why not @import + @define-color overrides: the compiled-in gtk-contained*.css
(GTK 3.24) has every Sass colour inlined as a literal; only one rule reads a
named colour, so overrides after the @import change lookup_color() but no
widget (verified 2026-11-07). So this script takes the stock stylesheet
VERBATIM from libgtk-3 and replaces COLOUR VALUES only (selectors, geometry,
gradients' structure, url()s untouched).

  python3 -I tools/gtk3-theme-gen.py --palette=gruvbox-material/palette.toml \
      --out=gruvbox-material/themes/Gruvbox-Material/gtk-3.0     # (just generate gruvbox-material)
  add --check to print stats and write nothing.

Mapping (see docs/theming.md): neutral greys follow a ramp from stock Adwaita
grey level to the Gruvbox Material surface ladder; coloured families (blue,
red, orange, green) keep their stock lightness relation to the family anchor
(selected_bg, error, warning, success) and are rebuilt around the palette
accent; white/foreground text on a coloured background becomes accent_fg.
Pure black/white alpha overlays and shadows are left alone (mode-invariant),
as in gtk-4.0/gtk.css.
The recolour engine is shared with tools/gtk4-theme-gen.py (tools/themegen.py).
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # python3 -I does not add the script dir
from themegen import arg, load_palette, recolour
import gi
gi.require_version('Gtk', '3.0')
from gi.repository import Gio, Gtk  # noqa: F401  (importing Gtk registers its resources)

if not arg('out'): sys.exit('usage: gtk3-theme-gen.py --palette=FILE --out=DIR [--check]   (DIR = <theme>/themes/<Name>/gtk-3.0)')
OUT = os.path.abspath(arg('out'))
RES = '/org/gtk/libgtk/theme/Adwaita/'
if not arg('palette'): sys.exit('--palette=FILE is required')
PAL = load_palette(arg('palette'))

HDR = '''/* Gruvbox Material GTK3 theme, %s variant (%s).
 * Built on GTK3's OWN built-in Adwaita stylesheet (/org/gtk/libgtk/theme/Adwaita/%s,
 * GTK 3.24.%d), taken verbatim and recoloured: ONLY colour values differ from
 * stock; selectors, geometry, gradients and url() references are unchanged.
 * Generated by tools/gtk3-theme-gen.py from the theme's palette.toml: edit the palette and
 * re-run `just generate`, do not hand-edit this file.
 * Licence: derived from GTK's stock stylesheet, so LGPL-2.0-or-later (Copyright GTK
 * contributors; see NOTICE and LICENSE in the repo). Palette: sainnhe/gruvbox-material (MIT).
 * Palette: Gruvbox Material, dark = MEDIUM backgrounds (window #32302f, view #282828,
 * buttons/headers #45403d, popovers #5a524c, fg #ddc7a1, accent #7daea3); light = the
 * hard-contrast block of gtk-4.0/gtk.css (view #f9f5d7, window #f5edca, accent #45707a).
 * Why not @import + @define-color: GTK 3.24's compiled Adwaita inlines its colours, so
 * named-colour overrides change nothing visible (see the script header).
 * The scale-with-marks and touch-selection-handle bitmaps in assets/ are the unmodified
 * stock PNGs (bitmaps keep their stock colour; check/radio/dash icons are recoloured by GTK).
 */
'''

def main():
    check = '--check' in sys.argv
    micro = Gtk.get_micro_version()
    os.makedirs(OUT + '/assets', exist_ok=True)
    for variant, src, dst in (('light', 'gtk-contained.css', 'gtk.css'), ('dark', 'gtk-contained-dark.css', 'gtk-dark.css')):
        stock = bytes(Gio.resources_lookup_data(RES + src, 0).get_data()).decode()
        new = HDR % (variant, 'medium backgrounds' if variant == 'dark' else 'hard backgrounds', src, micro) + recolour(stock, PAL[variant])
        print(dst, len(stock), '->', len(new), 'bytes')
        if not check:
            open(OUT + '/' + dst, 'w').write(new)
    if not check:
        for n in Gio.resources_enumerate_children(RES + 'assets', 0):
            data = Gio.resources_lookup_data(RES + 'assets/' + n, 0).get_data()
            open(OUT + '/assets/' + n, 'wb').write(bytes(data))

main()
