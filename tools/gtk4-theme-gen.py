"""Generate a scheme's pure-GTK4 theme from GTK4's own built-in stylesheet.

Scope: apps that use plain GTK 4 WITHOUT libadwaita (pavucontrol, gtkmm/GTK4 programs, ...).
libadwaita apps ignore the GTK theme and read only the user stylesheet
~/.config/gtk-4.0/gtk.css (see <scheme>/libadwaita/gtk.css).

Since GTK 4.24 the built-in theme is no longer "Adwaita": its resources are
/org/gtk/libgtk/theme/Default/{Default-light,Default-dark,Default-hc,Default-hc-dark}.css,
and the tiny gtk.css/gtk-dark.css only @import them behind prefers-color-scheme media
queries. This script takes Default-light.css and Default-dark.css VERBATIM and replaces
COLOUR VALUES only (selectors, geometry, url()s, calc() untouched), through the engine
shared with tools/gtk3-theme-gen.py (tools/themegen.py). Modern relative-colour functions
(rgb(from X r g b / calc(alpha * .4)), hsl(from X h calc(s * 1.2) ...)) keep their syntax;
only the origin colour X is recoloured. @define-color names are recoloured too (GTK4 keeps
them for compatibility, but the rules do not read them).

  python3 -I tools/gtk4-theme-gen.py --palette=gruvbox-material/palette.toml \
      --out=gruvbox-material/themes/Gruvbox-Material/gtk-4.0     # (just generate gruvbox-material)
  add --check to print stats and write nothing.

The palette is the same file as for GTK3 (stock GTK4 greys, blue #15539e, red #cc0000 and
orange #f57900 are the same anchors as GTK3's); GTK4-only stock colours (#26a269 success
green, #1f76e1 ...) are handled through [dark.exact]/[light.exact] entries there.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # python3 -I does not add the script dir
from themegen import arg, load_palette, load_meta, recolour, with_accent, accent_dir_write
import gi
gi.require_version('Gtk', '4.0')
from gi.repository import Gio, Gtk  # noqa: F401  (importing Gtk registers its resources)

if not arg('out'): sys.exit('usage: gtk4-theme-gen.py --palette=FILE --out=DIR [--accent-dir=DIR] [--check]   (DIR = <theme>/themes/<Name>/gtk-4.0)')
OUT = os.path.abspath(arg('out'))
RES = '/org/gtk/libgtk/theme/Default/'
if not arg('palette'): sys.exit('--palette=FILE is required')
PAL = load_palette(arg('palette'))
META = load_meta(arg('palette'))

HDR = '''/* %(title)s GTK4 theme (plain GTK 4, not libadwaita), %(variant)s variant%(note)s.
 * Built on GTK4's OWN built-in stylesheet (/org/gtk/libgtk/theme/Default/%(src)s,
 * GTK 4.%(mi)d.%(mc)d), taken verbatim and recoloured: ONLY colour values differ from
 * stock; selectors, geometry, calc(), gradients and url() references are unchanged.
 * Generated by tools/gtk4-theme-gen.py from the scheme's palette.toml (derived from its scheme.toml): edit
 * scheme.toml and re-run `just generate`, do not hand-edit this file. The accent can be switched afterwards
 * (`just switch-theme <scheme> <accent>`): sed token maps in <scheme>/accents/ rewrite the accent colours.
 * Licence: derived from GTK's stock stylesheet, so LGPL-2.0-or-later (Copyright GTK
 * contributors; see LICENSE in this theme folder and NOTICE in the repo). Palette: %(credit)s.
 * This file is read by GTK4 apps WITHOUT libadwaita; libadwaita apps use
 * ~/.config/gtk-4.0/gtk.css (libadwaita/gtk.css in the repo) instead.
 * The scale-with-marks and text-selection-handle bitmaps in assets/ are the unmodified
 * stock PNGs (bitmaps keep their stock colour; check/radio/dash icons are recoloured by GTK).
 */
'''

def main():
    check = '--check' in sys.argv
    mi, mc = Gtk.get_minor_version(), Gtk.get_micro_version()
    os.makedirs(OUT, exist_ok=True)     # the shared assets/ are written by tools/assets-gen.py, not per scheme
    plan = [('light', 'Default-light.css', 'gtk.css'), ('dark', 'Default-dark.css', 'gtk-dark.css')]
    if META['dark_only']: plan[0] = ('dark', 'Default-dark.css', 'gtk.css')     # see gtk3-theme-gen.py
    if META.get('light_only'): plan = plan[:1]
    adir = arg('accent-dir')
    for variant, src, dst in plan:
        stock = bytes(Gio.resources_lookup_data(RES + src, 0).get_data()).decode()
        note = ' (dark-only scheme: also used for the light slot)' if META['dark_only'] and dst == 'gtk.css' else ''
        hdr = HDR % dict(title=META['title'], variant=variant, note=note, src=src, mi=mi, mc=mc, credit=META['credit'])
        P = PAL[variant]
        new = hdr + recolour(stock, P)
        print(dst, len(stock), '->', len(new), 'bytes')
        if not check: open(OUT + '/' + dst, 'w').write(new)
        if adir:
            for a in P['accents']: accent_dir_write(adir, a, 'gtk-4.0/' + dst, hdr + recolour(stock, with_accent(P, a)))

main()
