"""Generate a scheme's libadwaita user stylesheet (<scheme>/libadwaita/gtk.css) from its palette.toml.

  python3 -I tools/libadwaita-gen.py --palette=<scheme>/palette.toml --out=<scheme>/libadwaita/gtk.css
        [--accent-dir=DIR]     # also write the six accent variants as DIR/<accent>/libadwaita/gtk.css

libadwaita apps ignore the GTK theme and read only ~/.config/gtk-4.0/gtk.css. This file changes none of
libadwaita's structural CSS: it only overrides the *_bg_color / *_fg_color named colours that libadwaita's own
(unmodified) stylesheet consumes, so the surface hierarchy (view < window < secondary sidebar < headerbar/sidebar <
dialog/popover < thumbnail, darkest to lightest in a dark scheme) matches stock Adwaita. The alpha-based dark card
overlay and the oklab()-derived *_color text variants are left to libadwaita. Pure Python, no gi needed.

Role mapping (roles from palette.toml [roles.<variant>]; light | dark):
  accent_bg = accent; accent_fg = accent_fg; destructive_bg = error_bg = red; success_bg = green; warning_bg = yellow
  (warning_fg = warning_fg; every other *_fg on a coloured fill = accent_fg); *_fg_color on surfaces = fg
  window = bg | bg;  view = bg_deep | bg_deep;  headerbar = bg_deep | surface (backdrop = bg | bg)
  sidebar = surface | surface (backdrop = surface_high | bg);  secondary sidebar = secondary_sidebar | bg (backdrop bg)
  card = bg_deep | alpha(white, .08);  dialog = bg | surface_high;  popover = popover (bg_deep | surface_high);
  thumbnail = bg_deep | surface_high.  toast (hard-coded dark in libadwaita) = dark surface_high on dark fg.
A dark-only scheme (dark_only = true) writes the dark values unconditionally, so the scheme stays dark.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # python3 -I does not add the script dir
from themegen import arg, load_meta, hx

if not arg('palette') or not arg('out'): sys.exit('usage: libadwaita-gen.py --palette=FILE --out=FILE [--accent-dir=DIR]')
META = load_meta(arg('palette'))
ROLES = META['roles']

HDR = '''/* %(title)s recolour of stock Adwaita/libadwaita named colours.
 *
 * Generated by tools/libadwaita-gen.py from the scheme's palette.toml (derived from its scheme.toml): edit
 * scheme.toml and re-run `just generate`, do not hand-edit this file. The accent can be switched afterwards
 * (`just switch-theme <scheme> <accent>`): sed token maps in <scheme>/accents/ rewrite the accent colours.
 *
 * This file changes NONE of libadwaita's structural CSS: it only overrides the literal *_bg_color / *_fg_color named
 * colours that libadwaita's own (unmodified) stylesheet consumes, so the surface hierarchy (view < window <
 * secondary_sidebar < headerbar/sidebar < dialog/popover < thumbnail, darkest to lightest in a dark scheme) matches
 * stock Adwaita, just recoloured. Structural helper colours (shade/border colours, the oklab()-derived *_color text
 * variants) are left alone: they are mode-invariant black/white alpha blends in stock Adwaita.
 *
 * Palette: %(credit)s.
%(mode)s */

'''
MODE_BOTH = ''' * Light/dark switching via @media (prefers-color-scheme: dark): GTK4 re-evaluates it live on every
 * org.gnome.desktop.interface color-scheme change.
'''
MODE_DARK = ''' * Dark-only scheme: the dark values apply unconditionally, whatever colour scheme the desktop asks for.
'''

def block(R, dark, indent=''):
    acc, acc_fg, fg = R['accent'], R['accent_fg'], R['fg']
    sec = R['secondary_sidebar']
    m = [
        ('accent_bg_color', acc), ('accent_fg_color', acc_fg), None,
        ('destructive_bg_color', R['red']), ('destructive_fg_color', acc_fg), None,
        ('success_bg_color', R['green']), ('success_fg_color', acc_fg), None,
        ('warning_bg_color', R['yellow']), ('warning_fg_color', R['warning_fg']), None,
        ('error_bg_color', R['red']), ('error_fg_color', acc_fg), None,
        ('window_bg_color', R['bg']), ('window_fg_color', fg), None,
        ('view_bg_color', R['bg_deep']), ('view_fg_color', fg), None,
        ('headerbar_bg_color', R['surface'] if dark else R['bg_deep']), ('headerbar_fg_color', fg), ('headerbar_backdrop_color', R['bg']), None,
        ('sidebar_bg_color', R['surface']), ('sidebar_fg_color', fg), ('sidebar_backdrop_color', R['bg'] if dark else R['surface_high']), None,
        ('secondary_sidebar_bg_color', sec), ('secondary_sidebar_fg_color', fg), ('secondary_sidebar_backdrop_color', R['bg']), None,
        ('card_bg_color', 'alpha(white, .08)' if dark else R['bg_deep']), ('card_fg_color', fg), None,
        ('dialog_bg_color', R['surface_high'] if dark else R['bg']), ('dialog_fg_color', fg), None,
        ('popover_bg_color', R['popover']), ('popover_fg_color', fg), None,
        ('thumbnail_bg_color', R['surface_high'] if dark else R['bg_deep']), ('thumbnail_fg_color', fg),
    ]
    out = []
    for e in m: out.append('' if e is None else '%s@define-color %s %s;' % (indent, e[0], e[1]))
    return '\n'.join(out) + '\n'

def toast(R):
    return '''
/* libadwaita hard-codes AdwToast as `toast { background: #505053; color: white; }` rather than going through any
 * *_bg_color named colour, so the overrides above cannot reach it. Like stock Adwaita it stays dark in light and
 * dark mode; the values are the dark popover surface and dark foreground. */
toast {
    background: %s;
    color: %s;
}
''' % (R['surface_high'], R['fg'])

def render(roles):
    dark_only = META['dark_only']; D = roles['dark']
    if dark_only:
        body = block(D, True) + toast(D)
        return HDR % dict(title=META['title'], credit=META['credit'], mode=MODE_DARK) + body
    L = roles['light']
    return (HDR % dict(title=META['title'], credit=META['credit'], mode=MODE_BOTH) + block(L, False)
            + '\n@media (prefers-color-scheme: dark) {\n' + block(D, True, '    ').replace('\n\n', '\n\n') + '}\n' + toast(D))

def with_accent_roles(roles, name):
    import copy
    r = copy.deepcopy(roles)
    for v in r:
        a = META['accents'][v][name]; r[v]['accent'] = a['color']; r[v]['accent_fg'] = a['fg']
    return r

text = render(ROLES)
if '--check' not in sys.argv:
    os.makedirs(os.path.dirname(os.path.abspath(arg('out'))), exist_ok=True)
    open(arg('out'), 'w').write(text)
if arg('accent-dir'):
    for n in META['accents']['dark']:
        p = os.path.join(arg('accent-dir'), n, 'libadwaita/gtk.css'); os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, 'w').write(render(with_accent_roles(ROLES, n)))
print('libadwaita', len(text), 'bytes')
